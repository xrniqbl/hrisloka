import { supabase } from '../lib/supabase';
import { guardCompanyId } from '../lib/tenantGuard';

// Get all assets — MANDATORY company scope
export async function getAllAssets(companyId) {
  if (!guardCompanyId(companyId, 'getAllAssets')) return { data: [], error: null };
  const { data, error } = await supabase
    .from('assets')
    .select('*, employees:assigned_to(name, division)')
    .eq('company_id', companyId)
    .order('created_at', { ascending: false });
  return { data: data || [], error };
}

// Get assets assigned to one employee (PWA) — MANDATORY company scope
export async function getMyAssets(employeeId, companyId) {
  if (!employeeId) return { data: [], error: null };
  if (!guardCompanyId(companyId, 'getMyAssets')) return { data: [], error: null };
  const { data, error } = await supabase
    .from('assets')
    .select('*')
    .eq('assigned_to', employeeId)
    .eq('company_id', companyId)
    .order('created_at', { ascending: false });
  return { data: data || [], error };
}

// Get asset by ID — optional companyId scope (defense in depth).
// assets HAS company_id (migration_phase4_security_complete.sql) so the
// filter applies directly; RLS remains primary.
export async function getAssetById(id, companyId = null) {
  let query = supabase
    .from('assets')
    .select('*, employees:assigned_to(name, division)')
    .eq('id', id);
  if (companyId) query = query.eq('company_id', companyId);
  const { data, error } = await (companyId ? query.maybeSingle() : query.single());
  return { data, error };
}

// Create asset — companyId resolved from asset.companyId (backward compat).
// Writes without a tenant are refused instead of inserting an unscoped row.
export async function createAsset(asset, companyId = null) {
  const resolvedCompanyId = companyId ?? asset?.companyId ?? null;
  if (!guardCompanyId(resolvedCompanyId, 'createAsset')) {
    return { data: null, error: { message: 'company_id required' } };
  }
  const { data, error } = await supabase
    .from('assets')
    .insert({
      // id is NOT accepted from client — auto-generated by database
      name: asset.name,
      category: asset.category,
      brand: asset.brand,
      serial: asset.serial,
      purchase_date: asset.purchaseDate,
      status: asset.status || 'available',
      assigned_to: asset.assignedTo || null,
      condition: asset.condition || 'Good',
      notes: asset.notes,
      company_id: resolvedCompanyId,
    })
    .select()
    .single();
  return { data, error };
}

// Update asset — MANDATORY company ownership
export async function updateAsset(id, asset, companyId) {
  if (!guardCompanyId(companyId, 'updateAsset')) return { data: null, error: { message: 'company_id required' } };
  const { data, error } = await supabase
    .from('assets')
    .update({
      name: asset.name,
      category: asset.category,
      brand: asset.brand,
      serial: asset.serial,
      purchase_date: asset.purchaseDate,
      status: asset.status,
      assigned_to: asset.assignedTo,
      condition: asset.condition,
      notes: asset.notes,
    })
    .eq('id', id)
    .eq('company_id', companyId)
    .select().single();
  return { data, error };
}

// Delete asset — MANDATORY company ownership
export async function deleteAsset(id, companyId) {
  if (!guardCompanyId(companyId, 'deleteAsset')) return { error: { message: 'company_id required' } };
  const { error } = await supabase.from('assets').delete().eq('id', id).eq('company_id', companyId);
  return { error };
}

// Assign asset to employee — MANDATORY company ownership
export async function assignAsset(assetId, employeeId, companyId) {
  if (!guardCompanyId(companyId, 'assignAsset')) {
    return { data: null, error: { message: 'company_id required' } };
  }
  const { data, error } = await supabase
    .from('assets')
    .update({ assigned_to: employeeId, status: 'in-use' })
    .eq('id', assetId)
    .eq('company_id', companyId)
    .select()
    .single();
  return { data, error };
}

// Unassign asset — MANDATORY company ownership
export async function unassignAsset(assetId, companyId) {
  if (!guardCompanyId(companyId, 'unassignAsset')) {
    return { data: null, error: { message: 'company_id required' } };
  }
  const { data, error } = await supabase
    .from('assets')
    .update({ assigned_to: null, status: 'available' })
    .eq('id', assetId)
    .eq('company_id', companyId)
    .select()
    .single();
  return { data, error };
}
